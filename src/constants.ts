// Added convertToHiragana to centralized constants
export const convertToHiragana = (text: string): string => {
  if (!text) return text;
  return text.replace(/[\u30a1-\u30f6]/g, (match) => String.fromCharCode(match.charCodeAt(0) - 0x60));
};

export const convertToKatakana = (text: string): string => {
  if (!text) return text;
  return text.replace(/[\u3041-\u3096]/g, (match) => String.fromCharCode(match.charCodeAt(0) + 0x60));
};

// Added getCategoryDisplayTitle to centralized constants to break circular dependencies
export const getCategoryDisplayTitle = (title: string, language: 'ja', isKatakana?: boolean): string => {
  if (isKatakana) {
    return convertToKatakana(title);
  }
  const hiragana = convertToHiragana(title);
  return hiragana;
};

export const getPublicUrl = () => {
  if (typeof window === 'undefined') return '';
  const origin = window.location.origin;
  
  // ais-dev- を ais-pre- に変換して、ゲストがアクセス可能なURLにする
  if (origin.includes('ais-dev-')) {
    return origin.replace('ais-dev-', 'ais-pre-');
  }
  
  return origin;
};
